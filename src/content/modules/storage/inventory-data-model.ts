const pk = (): SchemaTableColumn => ({ name: "id", pk: true, type: "text", required: true });

const branchRef = (required = true): SchemaTableColumn => ({
  name: "branch_id",
  type: "ref",
  required,
  fkTo: "branches",
  fkHref: `${GEN}#branches`,
});

const deptRef = (name = "requesting_department_id", required = true): SchemaTableColumn => ({
  name,
  type: "ref",
  required,
  fkTo: "departments",
  fkHref: `${GEN}#departments`,
});

const ref = (
  name: string,
  fkTo: string,
  required = false,
  fkHref?: string,
): SchemaTableColumn => ({
  name,
  type: "ref",
  required,
  fkTo,
  ...(fkHref ? { fkHref } : {}),
});

