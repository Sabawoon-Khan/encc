/**
 * Inventory Tables & ER — nested like Procurement / Payroll.
 * Crest Point Report §4.2 + North_Coal_ERP_Inventory_Forms.xlsx (IN-01…15).
 *
 * Ownership rules (read before editing):
 *  - Shared masters (branches, departments, positions) live on General Tables ER (fkHref).
 *  - PO / suppliers / the PC-01 `purchase_requests` queue live on Procurement ER. IN-04 is the
 *    SOURCE document (`inventory_purchase_requests`); it never becomes a second master — on transfer
 *    exactly one Procurement `purchase_requests` row is created with source_ref = IN-04 id.
 *  - Chart of accounts and the Control Log (FA-18) live on Finance ER; Inventory only stores refs.
 *  - Land / buildings are owned by Properties ER; Inventory owns their depreciation rate (IN-07/08).
 *  - Live stock (IN-11) is read from `stock_balances`, which is maintained from `stock_ledger_lines`.
 */
